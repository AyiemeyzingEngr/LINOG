#!/usr/bin/env node
/* Builds dist/linog_explainer.html: one standalone file with every script inlined and the fonts, logos and data
 * images embedded as base64 data URIs (no network access needed to view or render it).
 * Also (re)writes src/assets_index.js — the list of image assets and the real-data manifest — from assets/. */
const fs = require('fs');
const path = require('path');
const ROOT = __dirname;
const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp' };

/** src/assets_index.js: LINOG.ASSET_SRC (name → relative path) + LINOG.REAL_MANIFEST. Regenerated on every build/dev open. */
function writeAssetIndex() {
  const src = {};
  const logos = path.join(ROOT, 'assets', 'logos');
  if (fs.existsSync(logos)) for (const f of fs.readdirSync(logos).sort()) if (MIME[path.extname(f)]) src['logo:' + path.basename(f, path.extname(f))] = `assets/logos/${f}`;
  const manFile = path.join(ROOT, 'assets', 'data', 'manifest.json');
  const man = fs.existsSync(manFile) ? JSON.parse(fs.readFileSync(manFile, 'utf8')) : null;
  if (man) {
    src['data:focus'] = `assets/data/${man.focus.file}`;
    src['data:asc'] = `assets/data/${man.mosaic.ascending}`;
    src['data:desc'] = `assets/data/${man.mosaic.descending}`;
  }
  const js = `/* Generated by build.js from assets/ — do not edit. */\n(function () {\n  const L = (window.LINOG = window.LINOG || {});\n  L.ASSET_SRC = ${JSON.stringify(src, null, 2).replace(/\n/g, '\n  ')};\n  L.REAL_MANIFEST = ${JSON.stringify(man)};\n})();\n`;
  const out = path.join(ROOT, 'src', 'assets_index.js');
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== js) fs.writeFileSync(out, js);
  return src;
}

function build(out = path.join(ROOT, 'dist', 'linog_explainer.html')) {
  writeAssetIndex();
  let html = fs.readFileSync(path.join(ROOT, 'index.dev.html'), 'utf8');
  html = html.replace(/url\("(assets\/fonts\/[^"]+\.woff2)"\)/g, (_, p) => {
    const b64 = fs.readFileSync(path.join(ROOT, p)).toString('base64');
    return `url("data:font/woff2;base64,${b64}")`;
  });
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, p) => {
    let code = fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/<\/script/gi, '<\\/script');
    // embed every image the asset index points to
    code = code.replace(/"(assets\/(?:logos|data)\/[^"]+\.(?:png|jpg|webp))"/g, (m, a) => `"data:${MIME[path.extname(a)]};base64,${fs.readFileSync(path.join(ROOT, a)).toString('base64')}"`);
    return `<script>/* ${p} */\n${code}\n</script>`;
  });
  html = html.replace('<!--FONTS-->', '').replace('<!--/FONTS-->', '');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, html);
  return out;
}
module.exports = { build, writeAssetIndex };
if (require.main === module) {
  const out = build(process.argv[2]);
  console.log(`built ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
}
