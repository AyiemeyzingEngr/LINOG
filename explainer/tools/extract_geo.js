const topo = require('./topojson-client-3.1.0/package/dist/topojson-client.js');
const fs = require('fs');
const c10 = JSON.parse(fs.readFileSync('./world-atlas-2.0.2/package/countries-10m.json'));
const l110 = JSON.parse(fs.readFileSync('./world-atlas-2.0.2/package/land-110m.json'));
const l50 = JSON.parse(fs.readFileSync('./world-atlas-2.0.2/package/land-50m.json'));
function dp(pts, eps) { // Douglas-Peucker
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length-1] = 1;
  const st = [[0, pts.length-1]];
  while (st.length) { const [a,b] = st.pop(); let md=0, mi=-1;
    const [ax,ay]=pts[a],[bx,by]=pts[b]; const dx=bx-ax, dy=by-ay; const L=Math.hypot(dx,dy)||1e-12;
    for (let i=a+1;i<b;i++){ const d=Math.abs(dy*(pts[i][0]-ax)-dx*(pts[i][1]-ay))/L; if(d>md){md=d;mi=i;} }
    if (md>eps){ keep[mi]=1; st.push([a,mi],[mi,b]); } }
  return pts.filter((_,i)=>keep[i]);
}
function dpRing(r, eps){ // closed ring: split at the vertex farthest from r[0]
  let mi=0, md=-1; for (let i=1;i<r.length;i++){ const d=Math.hypot(r[i][0]-r[0][0], r[i][1]-r[0][1]); if(d>md){md=d;mi=i;} }
  const a=dp(r.slice(0,mi+1),eps), b=dp(r.slice(mi),eps); return a.concat(b.slice(1));
}
function area(r){let s=0;for(let i=0;i<r.length;i++){const [x1,y1]=r[i],[x2,y2]=r[(i+1)%r.length];s+=x1*y2-x2*y1;}return Math.abs(s/2);}
const ph = topo.feature(c10, c10.objects.countries).features.find(f => f.properties.name === 'Philippines');
let rings = [];
for (const poly of ph.geometry.coordinates) rings.push(poly[0]);
rings = rings.filter(r => area(r) > 0.004).map(r => dpRing(r, 0.006)).filter(r => r.length > 3);
rings.sort((a,b)=>area(b)-area(a));
const q = v => Math.round(v*1000)/1000;
const phOut = rings.map(r => r.flatMap(([x,y]) => [q(x), q(y)]));
console.error('PH rings', rings.length, 'pts', rings.reduce((s,r)=>s+r.length,0));
// regional land (50m) around PH for context: bbox 105..135, 0..26
const land50 = topo.feature(l50, l50.objects.land);
let reg = [];
for (const poly of land50.features[0].geometry.coordinates) { const r = poly[0];
  const inb = r.some(([x,y]) => x>104 && x<136 && y>-2 && y<27); if (!inb) continue;
  const rr = dpRing(r, 0.03); if (rr.length>3 && area(rr)>0.05) reg.push(rr); }
// drop PH from regional (approx: centroid in PH bbox)
reg = reg.filter(r => { const cx=r.reduce((s,p)=>s+p[0],0)/r.length, cy=r.reduce((s,p)=>s+p[1],0)/r.length; return !(cx>116.5&&cx<127&&cy>4.4&&cy<21.2); });
console.error('regional rings', reg.length, 'pts', reg.reduce((s,r)=>s+r.length,0));
const regOut = reg.map(r => r.flatMap(([x,y]) => [Math.round(x*100)/100, Math.round(y*100)/100]));
// world land 110m for globe
const land110 = topo.feature(l110, l110.objects.land);
let wl = [];
for (const poly of land110.features[0].geometry.coordinates) { const rr = dpRing(poly[0], 0.15); if (rr.length>3) wl.push(rr); }
console.error('world rings', wl.length, 'pts', wl.reduce((s,r)=>s+r.length,0));
const wOut = wl.map(r => r.flatMap(([x,y]) => [Math.round(x*10)/10, Math.round(y*10)/10]));
const js = `// Generated by tools/extract_geo.js from Natural Earth via world-atlas@2.0.2 (public domain).
// Rings are flat [lon,lat,lon,lat,...] arrays.
window.GEO_DATA = {
  ph: ${JSON.stringify(phOut)},
  region: ${JSON.stringify(regOut)},
  world: ${JSON.stringify(wOut)}
};
`;
fs.writeFileSync(process.argv[2], js);
console.error('bytes', js.length);
